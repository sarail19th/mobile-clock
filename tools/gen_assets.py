BG = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_assets.py. White fill; the widget tints it with setColorFilter and fades it with setImageAlpha. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="#FFFFFFFF" />
    <corners android:radius="{r}dp" />
</shape>
"""

BORDER = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_assets.py. Thin outline used for the "frosted" look. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <stroke android:width="1dp" android:color="#FFFFFFFF" />
    <corners android:radius="{r}dp" />
</shape>
"""

def main():
    (RES / "layout").mkdir(parents=True, exist_ok=True)
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    for key, name, font, extra in FONTS:
        for s in (0, 1):
            txt = LAYOUT.format(name=name, shadow_name="on" if s else "off", font=font,
                                extra=extra, shadow=SHADOW if s else "")
            (RES / "layout" / f"widget_{key}_s{s}.xml").write_text(txt, encoding="utf-8")
    for step in range(13):
        r = step * 4
        (RES / "drawable" / f"widget_bg_r{step}.xml").write_text(BG.format(r=r), encoding="utf-8")
        (RES / "drawable" / f"widget_bd_r{step}.xml").write_text(BORDER.format(r=r), encoding="utf-8")
    print("generated", len(FONTS) * 2, "layouts and", 26, "drawables")

if __name__ == "__main__":
    main()
