#!/usr/bin/env python3
"""
Generates the widget's resource files. RemoteViews cannot switch a typeface or a text shadow at
runtime, so there is one layout per (font, shadow) pair; corner radius is chosen from 13 pre-made shapes.

Run from the repo root after changing a template:   python3 tools/gen_assets.py
The outputs are committed, so a normal build never needs Python.
"""
